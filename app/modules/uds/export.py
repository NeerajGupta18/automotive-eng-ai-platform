"""Exporters: pytest (+ standalone harness), CAPL (experimental template), CSV."""
from __future__ import annotations

import csv
import io
import pprint
import zipfile
from pathlib import Path

HARNESS = Path(__file__).with_name("harness_template.py")


def _case_dicts(tests: list[dict], spec: dict) -> list[dict]:
    default = spec["sessions"][0]["id"]
    out = []
    for t in tests:
        p = t["payload"]
        out.append({"id": t["ref"], "title": p["title"], "category": p["category"], "element": p["element"],
                    "pre": {**p["pre"], "default_session": default}, "steps": p["steps"]})
    return out


def harness_text() -> str:
    return HARNESS.read_text()


def conftest_text() -> str:
    return '''"""Provide the `ecu` fixture for your test bench. See uds_harness.py for the adapter interface."""
import pytest


@pytest.fixture
def ecu():
    # Example (Linux SocketCAN + ISO-TP, untested skeleton):
    #   from uds_harness import SocketCanEcu
    #   return SocketCanEcu("can0", tx_id=0x7E0, rx_id=0x7E8, key_fn=my_seed_key_algorithm)
    raise NotImplementedError("implement the ecu fixture for your bench (send/reset/wait/compute_key)")
'''


def python_tests(spec_ref: str, spec_rev: int, spec: dict, tests: list[dict]) -> str:
    cases = _case_dicts(tests, spec)
    return (f'"""UDS tests generated for {spec["name"] or spec["ecu"]} (spec {spec_ref} rev {spec_rev}, version {spec["version"]}).\n'
            f'Expected results are derived from the approved specification by the platform oracle.\n'
            f'Do not edit expectations by hand: change the specification and regenerate.\n'
            f'{len(cases)} test cases. Run: pytest -v  (needs uds_harness.py and an `ecu` fixture in conftest.py)."""\n'
            f'import pytest\n\nfrom uds_harness import run_case\n\nTIMING = {spec["timing"]!r}\n\n'
            f'CASES = {pprint.pformat(cases, width=110, sort_dicts=False)}\n\n\n'
            '@pytest.mark.parametrize("case", CASES, ids=[c["id"] for c in CASES])\n'
            'def test_uds(ecu, case):\n'
            '    failures = run_case(ecu, case, TIMING)\n'
            '    assert not failures, "\\n".join(failures)\n')


def csv_text(tests: list[dict]) -> str:
    buf = io.StringIO()
    w = csv.writer(buf)
    w.writerow(["id", "element", "category", "title", "precondition", "steps", "expected", "status"])
    for t in tests:
        p = t["payload"]
        pre = f"session 0x{p['pre']['session']:02X}" + (f", unlocked level {p['pre']['unlock']}" if p["pre"]["unlock"] else "")
        steps = [s["req"] if "req" in s else f"wait {s['wait_ms']} ms" for s in p["steps"]]
        exp = [(" ".join(s["expect"]) or "no response") for s in p["steps"] if "req" in s]
        w.writerow([t["ref"], p["element"], p["category"], p["title"], pre, " | ".join(steps), " | ".join(exp), t["status"]])
    return buf.getvalue()


def _capl_bytes(tokens: list[str]) -> list[str]:
    return tokens


def capl_text(spec_ref: str, spec_rev: int, spec: dict, tests: list[dict]) -> str:
    t = spec["timing"]
    L = ["/*@!Encoding:1252*/",
         f"/* UDS tests for {spec['name'] or spec['ecu']} - spec {spec_ref} rev {spec_rev}. Generated by the platform.",
         "   EXPERIMENTAL: this template was NOT compiled or run in CANoe. Implement sendUds(), computeKey() and",
         "   enterPrecondition() for your configuration first (marked ADAPT), and review the test-report calls for your CANoe version. */",
         "includes {\n}\n", "variables {", f"  const long P2_MAX_MS = {t['p2_ms']};", f"  const long S3_MS = {t['s3_ms']};",
         "  byte gSeed[16];", "  long gSeedLen = 0;", "}\n",
         "/* ---- ADAPT: transport ------------------------------------------------- */",
         "// Send a raw UDS request, fill rsp[] and return the response length (0 = no response).",
         "long sendUds(byte req[], long reqLen, byte rsp[]) {", "  /* TODO: implement with your CANoe diagnostic configuration */", "  return 0;", "}\n",
         "void computeKey(long level, byte seed[], long seedLen, byte key[]) {", "  /* TODO: OEM seed-and-key algorithm */", "}\n",
         "void enterPrecondition(long session, long level) {",
         "  /* TODO: reset the ECU to the default session, send 10 <session>, then 27 <2*level-1> / 27 <2*level> <key> if level != 0 */", "}\n",
         "// expected value: 0..255 exact byte, -1 = any byte, -2 = any tail",
         "int matches(long exp[], long expLen, byte rsp[], long rspLen) {", "  long i;",
         "  if (expLen == 0) return rspLen == 0;", "  if (exp[expLen-1] == -2) {", "    if (rspLen < expLen-1) return 0;",
         "    for (i = 0; i < expLen-1; i++) if (exp[i] != -1 && exp[i] != rsp[i]) return 0;", "    return 1;", "  }",
         "  if (rspLen != expLen) return 0;", "  for (i = 0; i < expLen; i++) if (exp[i] != -1 && exp[i] != rsp[i]) return 0;",
         "  return 1;", "}\n"]

    def tok(t_):
        return "-1" if t_ == "??" else "-2" if t_ == "*" else f"0x{t_}"

    for t_ in tests:
        p = t_["payload"]
        name = t_["ref"].replace("-", "_")
        L += [f"testcase {name}() {{", f'  testCaseTitle("{t_["ref"]}", "{p["title"].replace(chr(34), chr(39))}");',
              "  byte req[64]; byte rsp[300]; byte keyb[16]; long exp[64]; long n; long i;",
              f"  enterPrecondition({p['pre']['session']}, {p['pre']['unlock'] or 0});"]
        for i, s in enumerate(p["steps"], start=1):
            if "wait_ms" in s:
                L.append(f"  testWaitForTimeout({s['wait_ms']});")
                continue
            parts = s["req"].split()
            marker = parts[-1] if parts[-1] in ("<KEY>", "<BADKEY>") else None
            raw = parts[:-1] if marker else parts
            for k, b in enumerate(raw):
                L.append(f"  req[{k}] = 0x{b};")
            n = len(raw)
            if marker:
                L += [f"  computeKey({int(raw[1], 16) // 2}, gSeed, gSeedLen, keyb);",
                      f"  for (i = 0; i < gSeedLen; i++) req[{n}+i] = keyb[i];"]
                if marker == "<BADKEY>":
                    L.append(f"  req[{n}] = req[{n}] ^ 0xFF;")
                L.append(f"  n = sendUds(req, {n} + gSeedLen, rsp);")
            else:
                L.append(f"  n = sendUds(req, {n}, rsp);")
            for k, e in enumerate(s["expect"]):
                L.append(f"  exp[{k}] = {tok(e)};")
            if raw[0] == "27" and len(raw) > 1 and int(raw[1], 16) % 2 == 1:
                L.append("  if (n > 2) { gSeedLen = n - 2; for (i = 0; i < gSeedLen; i++) gSeed[i] = rsp[2+i]; }")
            L += [f"  if (matches(exp, {len(s['expect'])}, rsp, n)) testStepPass(\"{t_['ref']}\", \"step {i} ok\");",
                  f"  else testStepFail(\"{t_['ref']}\", \"step {i}: unexpected response to {s['req']}\");"]
        L += ["}\n"]
    return "\n".join(L)


def bundle(spec_ref: str, spec_rev: int, spec: dict, tests: list[dict]) -> bytes:
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        z.writestr("test_uds_generated.py", python_tests(spec_ref, spec_rev, spec, tests))
        z.writestr("uds_harness.py", harness_text())
        z.writestr("conftest.py", conftest_text())
        z.writestr("uds_tests.can", capl_text(spec_ref, spec_rev, spec, tests))
        z.writestr("uds_tests.csv", csv_text(tests))
        z.writestr("README.txt", f"UDS test bundle for spec {spec_ref} rev {spec_rev}.\n"
                   "1. Implement the `ecu` fixture in conftest.py (send/reset/wait/compute_key).\n2. pip install pytest && pytest -v\n"
                   "3. uds_tests.can is an EXPERIMENTAL CAPL template (not compiled here); adapt the ADAPT blocks.\n"
                   "Expected results come from the approved specification; regenerate instead of editing them.\n")
    return buf.getvalue()
